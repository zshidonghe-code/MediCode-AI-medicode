def get_pinyin(text: str) -> str:
    try:
        from pypinyin import lazy_pinyin
        return "".join(w[0] for w in lazy_pinyin(text) if w)
    except Exception:
        return "".join(c for c in text if c.isascii())


def expand_file(data_dir: Path, filename: str, new_entries: list[tuple], version: str):
    """Read existing JSON, merge new entries, save back."""
    filepath = data_dir / filename
    with open(filepath, "r", encoding="utf-8") as f:
        existing = json.load(f)

    existing_codes = {e["code"] for e in existing}
    added = 0

    for code, name, category, aliases in new_entries:
        if code in existing_codes:
            continue
        existing_codes.add(code)
        entry = {
            "code": code,
            "name": name,
            "category": category,
            "version": version,
            "py": get_pinyin(name),
            "aliases": list(aliases),
        }
        existing.append(entry)
        added += 1

    # Sort by code
    existing.sort(key=lambda e: e["code"])

    # Backup original
    backup = filepath.with_suffix(".json.bak")
    with open(backup, "w", encoding="utf-8") as f:
        json.dump(existing, f, ensure_ascii=False, indent=2)

    # Save
    with open(filepath, "w", encoding="utf-8") as f:
        json.dump(existing, f, ensure_ascii=False, indent=2)

    return len(existing), added


